/*
  shopListCache
  - كاش بسيط بالذاكرة (مش localStorage) لحالة صفحة المتجر (Shop.jsx) -
    خانة وحدة بس (مش خريطة لكل تركيبة فلاتر ممكنة) لأنه الهدف الوحيد
    هو الحالة "السابقة مباشرة" يلي المستخدم رجع منها، مش أرشيف كامل
    لكل فلتر جرّبه من قبل - نفس فلسفة filterValuesCache.js بالضبط بس
    بشكل أبسط (كاش خانة وحدة لا خريطة)
  - الهدف: لما المستخدم يفتح منتج من شبكة المتجر ويرجع بزر رجوع
    المتصفح، القائمة (كل الصفحات المحمّلة عبر "تحميل المزيد") وموضع
    السكرول يرجعوا بالضبط متل ما كانوا، بدل ما تتحدث القائمة من الصفر
    من صفحة 1 وتضيع مكانه
  - المفتاح هو نص فلاتر الرابط (searchParams.toString()) - لو المستخدم
    غيّر الفلاتر فعليًا (بحث/فرز/فلتر جديد)، ما في تطابق مع المفتاح
    الجديد فبيصير جلب طبيعي من جديد من صفحة 1
  - الكاش بينمسح تلقائيًا لو المستخدم عمل Refresh كامل للصفحة (متغيّر
    بالذاكرة بس) - وهيدا مقصود، بيانات المتجر لازم تكون طازة بعد
    Refresh حقيقي، مش Bug
*/

let cache = null;

export const saveShopListState = (key, state) => {
  cache = { key, ...state };
};

export const getShopListState = (key) => {
  if (cache && cache.key === key) return cache;
  return null;
};
